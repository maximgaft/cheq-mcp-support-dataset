"""Stage 07 - choose the similarity floor that decides when to abstain, and
measure what it costs.

The floor is the number `find_similar_tickets` compares against: above it, return
precedents; below it, return no_precedent. Picking it by eye is how you end up
with a magic 0.7 nobody can defend, so it is derived here.

Three populations, not two:

  real tickets  - val split, written by the corpus generator. This is the shape
                  the tool receives in production, where a webhook delivers an
                  actual ticket, and it is what the floor is calibrated on.
  handwritten + - evals/abstention_queries.yaml, expect: precedent. Unambiguously
                  on topic, written by a person.
  handwritten - - the same file, expect: no_precedent. Off topic entirely.

The third population alone is not enough to calibrate against, and an earlier
version of this stage made exactly that mistake. Handwritten text scores lower
than generated text whatever its topic, so a set of handwritten negatives
measures provenance as much as relevance. The handwritten positives are the
control that separates the two effects - and they turn out to be about the same
size, which is the finding this stage exists to surface.

Rule: sit halfway between the highest-scoring off-topic query and the 5th
percentile of real tickets. Then report, rather than hide, how many handwritten
on-topic queries that floor wrongly rejects.
"""

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd
import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
from embedding import MODEL_NAME, center, document_text, embed_query

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data"
INDEX = DATA / "interim" / "06_index.npz"
SPLIT = DATA / "interim" / "05_split.parquet"
CASES = ROOT / "evals" / "abstention_queries.yaml"
OUT_JSON = DATA / "interim" / "07_thresholds.json"
OUT_REPORT = ROOT / "reports" / "calibration.md"

N_REAL = 400
SWEEP = [0.30, 0.35, 0.40, 0.45, 0.50, 0.55, 0.60]
SEED = 11


def main() -> None:
    blob = np.load(INDEX, allow_pickle=True)
    vectors, mean = blob["vectors"], blob["mean"]

    def top1(text: str) -> float:
        return float((vectors @ center(embed_query(text), mean)).max())

    cases = yaml.safe_load(CASES.read_text())
    positive = np.array([top1(c["query"]) for c in cases if c["expect"] == "precedent"])
    negative = np.array([top1(c["query"]) for c in cases if c["expect"] == "no_precedent"])

    val = pd.read_parquet(SPLIT)
    val = val[val.split.eq("val")].sample(N_REAL, random_state=SEED)
    real = np.array([top1(document_text(r.subject, r.body)) for _, r in val.iterrows()])

    greeting = top1("Dear Customer Support Team, I hope this message finds you well.")
    ceiling = float(negative.max())
    p5 = float(np.percentile(real, 5))
    floor = round(float((ceiling + p5) / 2), 2)

    provenance_gap = float(real.mean() - positive.mean())
    topic_gap = float(positive.mean() - negative.mean())
    false_reject = float((positive < floor).mean())

    report = [
        "# Similarity floor calibration",
        "",
        f"Generated by `pipeline/07_calibrate.py`. Model `{MODEL_NAME}`, centred vectors.",
        "",
        "## Populations",
        "",
        "| population | n | mean | min | max |",
        "|------------|--:|-----:|----:|----:|",
        f"| real tickets (generated) | {len(real)} | {real.mean():.3f} | {real.min():.3f} | {real.max():.3f} |",
        f"| handwritten, on topic | {len(positive)} | {positive.mean():.3f} | {positive.min():.3f} | {positive.max():.3f} |",
        f"| handwritten, off topic | {len(negative)} | {negative.mean():.3f} | {negative.min():.3f} | {negative.max():.3f} |",
        "",
        f"**Chosen floor: {floor:.2f}** - midpoint of the off-topic ceiling ({ceiling:.3f}) "
        f"and the real-ticket 5th percentile ({p5:.3f}).",
        "",
        "| floor | real accepted | handwritten on-topic accepted | off-topic accepted |",
        "|------:|--------------:|------------------------------:|-------------------:|",
    ]
    for t in sorted({*SWEEP, floor}):
        cells = (f"{t:.2f}", f"{100 * (real >= t).mean():.0f}%",
                 f"{100 * (positive >= t).mean():.0f}%", f"{100 * (negative >= t).mean():.0f}%")
        if t == floor:
            cells = tuple(f"**{c}**" for c in cells)
        report.append("| " + " | ".join(cells) + " |")

    report += [
        "",
        "## Two effects of the same size",
        "",
        f"The floor does separate topic: handwritten on-topic queries score "
        f"{topic_gap:+.3f} above handwritten off-topic ones. But generated text also "
        f"scores {provenance_gap:+.3f} above handwritten text *regardless of topic*. "
        "Those two effects are comparable in magnitude, and a single threshold on "
        "similarity cannot tell them apart.",
        "",
        f"So the floor is right for the input shape it was calibrated on, and wrong for "
        f"any other. On real tickets - the production shape, where a webhook delivers an "
        f"actual ticket - it accepts {100 * (real >= floor).mean():.0f}% and rejects "
        f"{100 * (1 - (negative >= floor).mean()):.0f}% of off-topic queries. Applied to a "
        f"hand-typed question it wrongly rejects **{100 * false_reject:.0f}%** of "
        f"legitimate on-topic ones.",
        "",
        "`find_similar_tickets` therefore applies the floor to `has_precedent` but returns "
        "the hits either way, and its guidance says that for a question typed by a person "
        "the floor is advisory rather than a refusal.",
        "",
        f"**The two populations genuinely overlap**, so no floor satisfies both: accepting "
        f"every on-topic query needs a floor at or below {positive.min():.3f}, and rejecting "
        f"every off-topic one needs it above {negative.max():.3f}. 0.40 is the visible "
        f"alternative - it accepts 100% of both legitimate populations and lets through 1 "
        f"of {len(negative)} off-topic queries. {floor:.2f} is the conservative end of that "
        "trade, chosen because a confidently wrong draft costs more than a refusal. Which "
        "end to sit at is a decision for whoever owns the support queue, not a "
        "property of the data.",
        "",
        "A related symptom: a bare corpus greeting with no content in it at all "
        '("Dear Customer Support Team, I hope this message finds you well.") scores '
        f"{greeting:.3f} - {'above' if greeting >= floor else 'just below'} the {floor:.2f} floor. "
        "Provenance alone carries a content-free string that close to the line.",
        "",
        "## Caveats",
        "",
        f"- The off-topic column is measured on {len(negative)} handwritten queries. A 0% "
        f"cell means zero of {len(negative)}, which bounds the true rate only loosely "
        f"(95% upper bound around {100 * (1 - 0.05 ** (1 / len(negative))):.0f}%).",
        f"- The on-topic set is {len(positive)} cases, and its minimum ({positive.min():.3f}) "
        f"overlaps the off-topic maximum ({negative.max():.3f}). No separate handwritten "
        "floor is fitted here - that would be fitting a threshold to a dozen points.",
        "- The corpus is ~40k synthetic tickets from one generator, so it is topically "
        "narrow and genuine no-precedent cases are rarer here than against a real archive.",
        "",
    ]

    print("\n".join(report[3:]))
    OUT_REPORT.parent.mkdir(parents=True, exist_ok=True)
    OUT_REPORT.write_text("\n".join(report))
    OUT_JSON.write_text(json.dumps({
        "similarity_floor": floor,
        "model": MODEL_NAME,
        "n_real": len(real),
        "n_handwritten_on_topic": len(positive),
        "n_handwritten_off_topic": len(negative),
        "real_accepted": round(float((real >= floor).mean()), 4),
        "handwritten_on_topic_accepted": round(float((positive >= floor).mean()), 4),
        "off_topic_accepted": round(float((negative >= floor).mean()), 4),
        "provenance_gap": round(provenance_gap, 4),
        "topic_gap": round(topic_gap, 4),
        "generated_by": "pipeline/07_calibrate.py",
    }, indent=2) + "\n")
    print(f"  wrote {OUT_JSON.relative_to(ROOT)} and {OUT_REPORT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()

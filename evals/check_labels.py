"""Check the committed answer labels against the 40 adjudicated ones.

Runs offline and needs no API key: both inputs are committed, so a reviewer can
reproduce every number the design note cites without spending $9.53.

The four-way taxonomy and the collapsed one are reported separately on purpose.
The four-way is unreliable, and the collapse is not - and the reason is worth
seeing rather than asserting.
"""

from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd
import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from pipeline.label import collapse  # noqa: E402

GOLD = ROOT / "evals" / "answer_labels.yaml"
LABELS = ROOT / "data" / "answer_labels.parquet"
REPORT = ROOT / "reports" / "labels.md"


def main() -> None:
    if not LABELS.exists():
        raise SystemExit(f"{LABELS.relative_to(ROOT)} not found - run `make label-all` first.")

    gold = {c["id"]: c for c in yaml.safe_load(GOLD.read_text())}
    labels = pd.read_parquet(LABELS).set_index("ticket_id")
    ids = [i for i in gold if i in labels.index]

    kind_hits = sum(labels.loc[i, "kind"] == gold[i]["label"] for i in ids)
    spec_ids = [i for i in ids if "ask_is_specific" in gold[i]
                and labels.loc[i, "kind"] == "information_request"]
    spec_hits = sum(bool(labels.loc[i, "ask_is_specific"]) == gold[i]["ask_is_specific"]
                    for i in spec_ids)

    mine = {i: collapse(gold[i]["label"], gold[i].get("ask_is_specific")) for i in ids}
    model = {i: collapse(labels.loc[i, "kind"], bool(labels.loc[i, "ask_is_specific"]))
             for i in ids}
    collapsed_hits = sum(mine[i] == model[i] for i in ids)

    full = labels.assign(state=[collapse(k, bool(s))
                                for k, s in zip(labels.kind, labels.ask_is_specific)])
    share = full.state.value_counts(normalize=True)
    mine_share = pd.Series(list(mine.values())).value_counts(normalize=True)

    lines = [
        "# Answer labels — agreement with the adjudicated set",
        "",
        "Generated by `evals/check_labels.py`. Offline, no API key: it compares the "
        "committed `data/answer_labels.parquet` (Claude Haiku 4.5, 39,739 answers, $9.53) "
        f"against the {len(gold)} tickets in `evals/answer_labels.yaml` that I read and "
        "labelled by hand.",
        "",
        "| | agreement |",
        "|---|---:|",
        f"| `kind`, four-way | **{kind_hits}/{len(ids)}** ({100 * kind_hits / len(ids):.0f}%) |",
        f"| `ask_is_specific`, on information requests | {spec_hits}/{len(spec_ids)} "
        f"({100 * spec_hits / len(spec_ids):.0f}%) |",
        f"| collapsed to resolved / actionable_ask / dead_end | **{collapsed_hits}/{len(ids)}** "
        f"({100 * collapsed_hits / len(ids):.0f}%) |",
        "",
        "## Where the four-way fails",
        "",
        "| mine ↓ / model → | " + " | ".join(sorted({*mine.values(), *model.values()})) + " |",
    ]
    kinds = sorted({gold[i]["label"] for i in ids} | set(labels.loc[ids, "kind"]))
    confusion = pd.crosstab(
        pd.Series([gold[i]["label"] for i in ids]),
        pd.Series([labels.loc[i, "kind"] for i in ids]),
    ).reindex(index=kinds, columns=kinds, fill_value=0)
    lines = lines[:-1] + [
        "| mine ↓ / model → | " + " | ".join(f"`{k}`" for k in kinds) + " |",
        "|---" * (len(kinds) + 1) + "|",
        *[f"| `{row}` | " + " | ".join(str(confusion.loc[row, c]) for c in kinds) + " |"
          for row in kinds],
        "",
        "`information_request` is recalled perfectly; `acknowledgement` is where the model "
        "scatters. Corpus-wide it calls "
        f"{100 * labels.kind.eq('information_request').mean():.0f}% information requests where "
        f"the adjudicated sample says {100 * sum(1 for i in ids if gold[i]['label'] == 'information_request') / len(ids):.0f}%, "
        "so it over-calls the class it never misses.",
        "",
        "## The four-way labels across the corpus",
        "",
        "| `kind` | share of 39,739 labelled answers |",
        "|---|---:|",
        *[f"| `{k}` | {100 * v:.1f}% |" for k, v in labels.kind.value_counts(normalize=True).items()],
        "",
        "`not_a_support_reply` is customer text sitting in the answer column; those rows are "
        "unusable as precedent and count as dead ends.",
        "",
        "## Why the collapsed view is still usable",
        "",
        "That confusion moves tickets *within* `dead_end` — a vague ask and a bare "
        "acknowledgement are both dead ends — so the dominant error cancels at the level "
        "the business claim uses. Two independent estimates:",
        "",
        "| state | model, 39,739 | adjudicated, n=40 |",
        "|---|---:|---:|",
        *[f"| `{s}` | {100 * share.get(s, 0):.1f}% | {100 * mine_share.get(s, 0):.1f}% |"
          for s in ("dead_end", "actionable_ask", "resolved")],
        "",
        f"**About half of all first replies are dead ends** — they neither resolve the ticket "
        f"nor tell the customer what to send, so each one costs a round trip and buys nothing. "
        f"The four-way labels should not be quoted on their own at {100 * kind_hits / len(ids):.0f}% "
        "agreement; this collapse is what the design note reports.",
        "",
        f"Caveat: n={len(ids)} adjudicated tickets. The intervals are wide, which is why the two "
        "estimates agreeing to within a few points is the claim, not either number alone.",
        "",
    ]
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text("\n".join(lines))
    print("\n".join(lines[3:]))
    print(f"  wrote {REPORT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
